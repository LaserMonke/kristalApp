typedef _Responder =
    Future<http.StreamedResponse> Function(http.BaseRequest request, String body);

class _Harness {
  _Harness({
    required this.repo,
    required this.cache,
    required this.prefs,
    required this.http,
  });

  final SupabaseProgressRepo repo;
  final LocalProgressRepo cache;
  final SharedPreferences prefs;
  final _FakeHttpClient http;
}

class _Recorded {
  _Recorded(this.method, this.url, this.body);

  final String method;
  final Uri url;
  final String body;
}

/// Stands in for the network so no test ever opens a socket.
class _FakeHttpClient extends http.BaseClient {
  _FakeHttpClient(this._responder);

  final _Responder _responder;
  final List<_Recorded> recorded = <_Recorded>[];

  @override
  Future<http.StreamedResponse> send(http.BaseRequest request) async {
    final String body = request is http.Request ? request.body : '';
    recorded.add(_Recorded(request.method, request.url, body));

    final http.StreamedResponse response = await _responder(request, body);
    // postgrest reads `response.request` while parsing, so echo it back.
    return http.StreamedResponse(
      response.stream,
      response.statusCode,
      contentLength: response.contentLength,
      headers: response.headers,
      request: request,
    );
  }
}

Future<http.StreamedResponse> _json(Object? payload, {int status = 200}) async {
  final List<int> bytes = utf8.encode(jsonEncode(payload));
  return http.StreamedResponse(
    Stream<List<int>>.value(bytes),
    status,
    contentLength: bytes.length,
    headers: <String, String>{'content-type': 'application/json'},
  );
}
